export function calcularOrcamentoPersiana(peca) {
  const modelo = peca.produto === "Persiana" ? peca.modelo : null;
  if (!MODELOS_PERSIANA_COM_ORCAMENTO.includes(modelo)) return { usa: false };

  const orc = { ...orcamentoPersianaPadrao(), ...(peca.orcamentoPersiana || {}) };
  const largTotal = peca.largura > 0 ? peca.largura : null;
  const alt = peca.altura > 0 ? peca.altura : null;
  const itens = listarItensPersiana(modelo, orc);
  const item = itens.find((i) => i.id === orc.item) || null;
  const regras = regrasDe(modelo, orc, item);
  // Largura acima do máximo da fábrica: dá pra dividir em 2 persianas
  // iguais (cada uma com metade da largura, cobradas separadamente).
  const podeDividir = !!regras.larMax && largTotal != null && largTotal > regras.larMax + 1e-9;
  const n = podeDividir && orc.dividir ? 2 : 1;
  const larg = largTotal != null ? largTotal / n : null;
  const faltas = [];
  const avisos = [];
  const linhas = [];

  if (modelo === "Horizontal" && !orc.linha) faltas.push("a espessura da lâmina (50, 25 ou 16 mm)");
  if (precisaVariante(modelo, orc) && !orc.variante) faltas.push(modelo === "Painel" ? "o número de vias" : "cadarço ou fita");
  if (!item) faltas.push("o tecido/coleção");
  else if (item.preco == null) avisos.push(item.aDefinir ? "Esta coleção está com o preço ilegível na tabela — confirme com o fornecedor e digite o valor manualmente." : "Sem preço na tabela para esta combinação.");
  if (larg == null) faltas.push("a largura");
  if (alt == null) faltas.push("a altura");

  // Bandô normal / Guia Niveladora: a cor é obrigatória quando marcados.
  opcoesDoModelo(modelo, orc).forEach((op) => {
    if (op.cor && opcaoAtiva(modelo, orc, op) && !orc.cores?.[op.id]) faltas.push(`a cor de "${op.rotulo.split(" (")[0]}"`);
  });

  const pronto = faltas.length === 0 && item && item.preco != null;
  let areaReal = null;
  let areaCobrada = null;
  let total = null;

  if (larg != null && alt != null) {
    areaReal = arred(larg * alt);
    const altCobrada = Math.max(alt, regras.altMin || 0);
    areaCobrada = arred(Math.max(larg * altCobrada, regras.areaMin || 0));
    if (regras.larMin && larg < regras.larMin) avisos.push(`Largura abaixo do mínimo de ${fmt2(regras.larMin)} m.`);
    if (regras.larMax && larg > regras.larMax) avisos.push(`Largura acima do máximo de ${fmt2(regras.larMax)} m para este item.`);
    if (regras.altMinReal && alt < regras.altMinReal) avisos.push(`Altura abaixo do mínimo de ${fmt2(regras.altMinReal)} m.`);
    if (regras.altMax && alt > regras.altMax) avisos.push(`Altura acima do máximo de ${fmt2(regras.altMax)} m.`);
    if (regras.areaMax && areaReal > regras.areaMax) avisos.push(`Área acima do máximo de ${fmt2(regras.areaMax)} m² por persiana.`);
  }

  if (pronto) {
    const fator = item.st ? 1 + CONFIG.st : 1;
    const base = arred(areaCobrada * item.preco * fator);
    const cobrouMinimo = areaCobrada > areaReal + 1e-9;
    // Com a largura dividida, cada linha "por persiana" vale 2×.
    const empurra = (l) =>
      linhas.push(n > 1 ? { ...l, detalhe: `${n} persianas${l.detalhe ? " · " + l.detalhe : ""}`, valor: arred(l.valor * n) } : l);
    empurra({
      rotulo: "Persiana",
      detalhe: `${fmt2(areaCobrada)} m²${cobrouMinimo ? " (mínimo cobrado)" : ""} × ${fmtBRL(arred(item.preco * fator))}${n > 1 ? ` · cada uma com ${fmt2(larg)} m` : ""}`,
      valor: base,
    });
    const baseSemTaxa = areaCobrada * item.preco;
    const pctLinha = (rotulo, pct) => empurra({ rotulo, detalhe: `+${fmtNum(pct)}%`, valor: arred((baseSemTaxa * pct * fator) / 100) });

    // Acréscimos automáticos por largura
    if (modelo === "Rolo" || modelo === "Stripe") {
      if (larg > 2.5) pctLinha("Tubo de 50 mm (largura acima de 2,50 m)", 15);
      else if (modelo === "Rolo" && larg > 2.2) pctLinha("Tubo de 40 mm (largura acima de 2,20 m)", 10);
    }
    if (modelo === "Celular" && larg > 1.8) pctLinha("Largura acima de 1,80 m", 20);

    // Opções marcadas
    const medidas = { larg, alt, variante: orc.variante };
    opcoesDoModelo(modelo, orc).forEach((op) => {
      if (op.grupos && !op.grupos.includes(item.grupo)) return;
      if (op.requer && !opcaoAtiva(modelo, orc, OPCOES[modelo].find((o) => o.id === op.requer))) return;
      if (!opcaoAtiva(modelo, orc, op)) return;
      const v = typeof op.valor === "function" ? op.valor(medidas) : op.valor;
      const corTxt = op.cor && orc.cores?.[op.id] ? ` — ${orc.cores[op.id]}` : "";
      if (v == null && op.aDefinir) {
        // Item ainda sem preço na tabela: entra na lista com valor zero e avisa.
        linhas.push({ rotulo: op.rotulo.split(" (")[0] + corTxt, detalhe: "preço a definir", valor: 0 });
        avisos.push(`"${op.rotulo.split(" (")[0]}" ainda está sem preço cadastrado — o total não inclui este item.`);
        return;
      }
      if (v == null) {
        avisos.push(`"${op.rotulo}" não tem preço para estas medidas — confira a tabela.`);
        return;
      }
      if (op.altMax && alt > op.altMax) avisos.push(`"${op.rotulo}": altura acima do limite de ${fmt2(op.altMax)} m.`);
      if (op.tipo === "pct") pctLinha(op.rotulo, v);
      else if (op.tipo === "qtd-pct") {
        const q = Math.max(0, parseInt(orc.qtd?.[op.id], 10) || 0);
        if (q > 0) pctLinha(`${op.rotulo.split(" (")[0]} ×${q}`, v * q);
      } else if (op.tipo === "fixo") empurra({ rotulo: op.rotulo.split(" (")[0] + corTxt, detalhe: "", valor: arred(v) });
      else if (op.tipo === "ml-lar") empurra({ rotulo: op.rotulo.split(" (")[0] + corTxt, detalhe: `${fmt2(larg)} m × ${fmtBRL(v)}`, valor: arred(larg * v) });
      else if (op.tipo === "ml-alt") empurra({ rotulo: op.rotulo.split(" (")[0] + corTxt, detalhe: `${fmt2(alt)} m × ${fmtBRL(v)}`, valor: arred(alt * v) });
    });

    // Motor + controle
    const motor = MOTORES.find((m) => m.id === orc.motor && m.modelos.includes(modelo));
    if (motor) {
      if (motor.preco == null) avisos.push(`${motor.rotulo}: preço ilegível na tabela — digite em "Outros valores".`);
      else {
        const extraRomana = modelo === "Romana" && motor.romanaExtra ? TAB.motorRomanaExtra : 0;
        empurra({ rotulo: motor.rotulo, detalhe: extraRomana ? `inclui +${fmtBRL(extraRomana)} p/ Romana` : "", valor: arred(motor.preco + extraRomana) });
      }
      if (motor.areaMax && areaReal > motor.areaMax) avisos.push(`Motor indicado para até ${fmtNum(motor.areaMax)} m².`);
      acessoriosDoMotor(motor.id).forEach((a) => {
        if (orc.acessorios?.[a.id]) empurra({ rotulo: a.rotulo, detalhe: "", valor: a.preco });
      });
    }
    const controle = CONTROLES.find((c) => c.id === orc.controle);
    if (controle) linhas.push({ rotulo: controle.rotulo, detalhe: "", valor: controle.preco });

    if (orc.extra > 0) linhas.push({ rotulo: "Outros valores", detalhe: "informado à mão", valor: arred(orc.extra) });

    total = arred(linhas.reduce((s, l) => s + l.valor, 0));
  }

  return { usa: true, pronto: !!pronto, faltas, avisos, linhas, total, areaReal, areaCobrada, item, itens, orc, podeDividir, dividido: n > 1, larguraPorPersiana: larg, larguraMaxima: regras.larMax || null };
}

function fmt2(n) {
  return n.toFixed(2).replace(".", ",");
}
function fmtNum(n) {
  return String(Math.round(n * 100) / 100).replace(".", ",");
}
function fmtBRL(v) {
  return "R$ " + v.toLocaleString("pt-BR", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

function precoOpcao(grupo, id) {
  return OPCOES[grupo].find((o) => o.id === id).valor;
}

/* ============================================================
   PREÇOS NO SUPABASE
   ------------------------------------------------------------
   Igual às cortinas: os NÚMEROS ficam na tabela `precos_orcamento`
   (chave → preço) e as REGRAS (mínimos, acréscimos em %, limites) ficam
   aqui no código. Os valores escritos neste arquivo são só a reserva —
   se a tabela estiver vazia ou inacessível, o orçamento continua
   funcionando com eles. Chaves das persianas começam com "persiana_".
   ============================================================ */
function registroPrecos() {
  const reg = [];
  const usadas = new Set();
  const add = (chave, categoria, descricao, unidade, get, set) => {
    let k = chave;
    for (let n = 2; usadas.has(k); n++) k = `${chave}_${n}`;
    usadas.add(k);
    reg.push({ chave: k, categoria, descricao, unidade, get, set });
  };
  const nomeCompleto = (x) => x.nome;
  const campo = (obj, f, chave, cat, desc, un) => add(chave, cat, desc, un, () => obj[f], (v) => (obj[f] = v));

  add("persiana_st_percentual", "persiana_geral", "Substituição tributária (%) — PVC, alumínio e sintético", "%", () => Math.round(CONFIG.st * 1e6) / 1e4, (v) => (CONFIG.st = v / 100));

  DADOS.especiais.forEach((x) => {
    const chaveBase = slug(`${x.nome} ${x.cores}`).replace(/-/g, "_");
    [["rolo", "Rolo", true], ["romana", "Romana", false], ["cascade", "Cascade", false]].forEach(([f, rot, aceitaNulo]) => {
      const aDefinir = f === "rolo" && x[f] == null && (x.nome === "AM 2861" || x.nome === "Bk 4340");
      if (x[f] == null && !aDefinir) return;
      campo(x, f, `persiana_${f}_${chaveBase}`, `persiana_${f}`, `${rot} — ${nomeCompleto(x)}`, "m2");
    });
  });
  DADOS.stripe.forEach((x) => campo(x, "preco", `persiana_stripe_${slug(`${x.nome} ${x.cores}`).replace(/-/g, "_")}`, "persiana_stripe", `Stripe — ${nomeCompleto(x)}`, "m2"));
  DADOS.painel.forEach((x) => {
    const b = slug(`${x.nome} ${x.cores}`).replace(/-/g, "_");
    [["v2", 2], ["v3", 3], ["v4", 4]].forEach(([f, n]) => campo(x, f, `persiana_painel_${n}vias_${b}`, "persiana_painel", `Painel ${n} vias — ${nomeCompleto(x)}`, "m2"));
  });
  DADOS.ph50.forEach((x) => {
    const b = slug(`${x.nome} ${x.cores}`).replace(/-/g, "_");
    campo(x, "cadarco", `persiana_ph50_cadarco_${b}`, "persiana_horizontal", `Horizontal 50 mm cadarço — ${nomeCompleto(x)}`, "m2");
    campo(x, "fita", `persiana_ph50_fita_${b}`, "persiana_horizontal", `Horizontal 50 mm fita — ${nomeCompleto(x)}`, "m2");
  });
  DADOS.ph25.forEach((x) => campo(x, "prazo", `persiana_ph${x.esp}_${slug(x.nome).replace(/-/g, "_")}`, "persiana_horizontal", `Horizontal ${x.esp} mm — ${x.nome} (a prazo)`, "m2"));
  DADOS.vertical.forEach((x) => campo(x, "prazo", `persiana_vertical_${slug(`${x.nome} ${x.cores}`).replace(/-/g, "_")}`, "persiana_vertical", `Vertical ${x.grp} — ${nomeCompleto(x)} (a prazo)`, "m2"));
  DADOS.celular.forEach((x) => campo(x, "prazo", `persiana_celular_${slug(x.nome).replace(/-/g, "_")}`, "persiana_celular", `Celular — ${x.nome} (a prazo)`, "m2"));

  const uni = { fixo: "un", "ml-lar": "m", "ml-alt": "m" };
  Object.entries(OPCOES).forEach(([grupo, lista]) => {
    if (grupo === "Horizontal-16") return; // mesma lista da Horizontal-25
    lista.forEach((op) => {
      if (typeof op.valor !== "number" || op.tipo === "pct" || op.tipo === "qtd-pct") return;
      campo(op, "valor", `persiana_opc_${slug(grupo).replace(/-/g, "_")}_${op.id.toLowerCase()}`, "persiana_opcional", `${grupo} — ${op.rotulo}`, uni[op.tipo]);
    });
  });
  campo(TAB.monocomando50, "ate180", "persiana_opc_horizontal_50_monocomando_ate_1_80", "persiana_opcional", "Horizontal 50 mm — monocomando (largura até 1,80 m)", "un");
  campo(TAB.monocomando50, "ate220", "persiana_opc_horizontal_50_monocomando_ate_2_20", "persiana_opcional", "Horizontal 50 mm — monocomando (largura até 2,20 m)", "un");
  [2, 3, 4].forEach((n) => campo(TAB.trilhoPainel, n, `persiana_opc_painel_trilho_${n}vias`, "persiana_opcional", `Painel — trilho montado ${n} vias`, "m"));
  campo(TAB, "motorRomanaExtra", "persiana_motor_romana_extra", "persiana_motor", "Acréscimo no motor Somfy Sonesse/LSN 40 quando a persiana é Romana", "un");
  MOTORES.forEach((m) => campo(m, "preco", `persiana_motor_${m.id.replace(/-/g, "_")}`, "persiana_motor", m.rotulo, "un"));
  CONTROLES.forEach((c) => campo(c, "preco", `persiana_controle_${c.id.replace(/-/g, "_")}`, "persiana_motor", c.rotulo, "un"));
  MOTOR_ACESSORIOS.forEach((a) => campo(a, "preco", `persiana_acessorio_${a.id}`, "persiana_motor", a.rotulo, "un"));
  return reg;
}

// Aplica por cima dos valores do código o que veio da tabela do Supabase.
export function aplicarPrecosPersiana(mapa) {
  if (!mapa) return;
  registroPrecos().forEach((r) => {
    if (mapa[r.chave] != null && Number.isFinite(mapa[r.chave])) r.set(mapa[r.chave]);
  });
}

// Usado só para gerar o SQL inicial (linhas que ainda não têm preço no
// código, "a definir", ficam de fora porque a coluna preco não aceita nulo).
export function linhasPrecosPersiana() {
  return registroPrecos()
    .filter((r) => r.get() != null)
    .map((r) => ({ chave: r.chave, categoria: r.categoria, descricao: r.descricao, preco: r.get(), unidade: r.unidade }));
}
export function chavesPrecosPersianaADefinir() {
  return registroPrecos()
    .filter((r) => r.get() == null)
    .map((r) => ({ chave: r.chave, descricao: r.descricao, unidade: r.unidade, categoria: r.categoria }));
}
