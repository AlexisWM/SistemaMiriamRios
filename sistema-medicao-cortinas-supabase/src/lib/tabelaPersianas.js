// Regras por modelo: área mínima cobrada (m²), altura mínima cobrada (m) e
// limites de medida (só geram AVISO — a pessoa pode ter autorização).
function regrasDe(modelo, orc, item) {
  switch (modelo) {
    case "Rolo":
    case "Romana":
    case "Cascade":
      return { areaMin: 1.2, altMin: 1.0, larMax: item?.larMax || null };
    case "Stripe":
      return { areaMin: 1.2, altMin: 1.0, larMin: 0.8, larMax: item?.larMax || null, altMax: 4.0 };
    case "Painel":
      return { areaMin: 1.5, altMin: 1.5, larMax: 5.0 };
    case "Vertical":
      return { areaMin: 1.5, altMin: 1.5, altMax: item?.grupo === "PVC" ? 3.0 : 3.5 };
    case "Celular":
      return { larMax: 2.5 };
    case "Horizontal":
      if (orc.linha === "50") {
        const g = item?.grupo;
        if (g === "PVC") return { areaMin: 1.2, altMin: 1.0, larMin: 0.6, larMax: 2.2, altMinReal: 0.4, altMax: 2.8, areaMax: 3.5 };
        if (g === "Natural" || g === "Sintética") return { areaMin: 1.2, altMin: 1.0, larMin: 0.6, larMax: 2.0, altMinReal: 0.6, altMax: 2.8, areaMax: 3.0 };
        return { areaMin: 1.2, altMin: 1.0, larMin: 0.6, larMax: 2.2, altMinReal: 0.6, altMax: 2.8, areaMax: 4.0 };
      }
      if (orc.linha === "25") return { areaMin: 1.0, altMin: 1.0, larMax: 2.7, areaMax: 5.0 };
      if (orc.linha === "16") return { areaMin: 1.0, altMin: 1.0, larMax: 2.3, areaMax: 4.0 };
      return {};
    default:
      return {};
  }
}

// Itens (tecido/coleção/material) disponíveis para o modelo — já com o
// preço por m² certo para a variante escolhida.
export function listarItensPersiana(modelo, orc) {
  const lista = [];
  const add = (grupo, nome, cores, preco, extra = {}) =>
    lista.push({ id: slug(`${modelo}-${orc.linha || ""}-${grupo}-${nome}-${cores}`), grupo, nome, cores, preco, ...extra });
  if (modelo === "Rolo" || modelo === "Romana" || modelo === "Cascade") {
    const chave = modelo === "Rolo" ? "rolo" : modelo === "Romana" ? "romana" : "cascade";
    DADOS.especiais.forEach((x) => {
      const p = x[chave];
      const aDefinir = modelo === "Rolo" && p == null && (x.nome === "AM 2861" || x.nome === "Bk 4340");
      if (p == null && !aDefinir) return;
      add(x.cls, x.nome, x.cores, p, { larMax: x.larMax, aDefinir });
    });
  } else if (modelo === "Stripe") {
    DADOS.stripe.forEach((x) => add(x.cls, x.nome, x.cores, x.preco, { larMax: x.larMax }));
  } else if (modelo === "Painel") {
    DADOS.painel.forEach((x) => add(x.cls, x.nome, x.cores, orc.variante === "3" ? x.v3 : orc.variante === "4" ? x.v4 : orc.variante === "2" ? x.v2 : null));
  } else if (modelo === "Vertical") {
    DADOS.vertical.forEach((x) => add(x.grp, x.nome, x.cores, x.prazo, { st: x.grp === "PVC" }));
  } else if (modelo === "Celular") {
    DADOS.celular.forEach((x) => add(x.grp, x.nome, x.cores, x.prazo));
  } else if (modelo === "Horizontal") {
    if (orc.linha === "50") {
      DADOS.ph50.forEach((x) => {
        const p = orc.variante === "fita" ? x.fita : orc.variante === "cadarco" ? x.cadarco : null;
        add(x.grp, x.nome, x.cores, p, { st: x.grp !== "Natural" });
      });
    } else if (orc.linha === "25" || orc.linha === "16") {
      DADOS.ph25.filter((x) => x.esp === orc.linha).forEach((x) => add(`${orc.linha} mm`, x.nome, "", x.prazo, { st: true }));
    }
  }
  return lista;
}

